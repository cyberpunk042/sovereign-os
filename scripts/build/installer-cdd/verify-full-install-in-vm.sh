#!/usr/bin/env bash
# Run the DEBIAN d-i install TO COMPLETION in a VM and inspect what it produced.
#
# WHY THIS EXISTS.
#
# Three sovereign-os installs booted on the operator's machine — custom znver5
# kernel, 24 CPUs, 261 GB RAM, ZERO failed units — and showed nothing. Each took
# 18 minutes to discover. The ISO built, the install "succeeded", and the only
# way to learn otherwise was to reboot real hardware and stare at a black
# screen. The fourth attempt corrupted the other NVMe's bootloader.
#
# Nothing downstream of the disk pick had ever been exercised before the
# operator's own machine exercised it:
#
#   * do the late_command steps actually run?
#   * does the custom znver5 kernel land via dpkg -i from the CD pool?
#   * does `nomodeset` reach the INSTALLED /boot/grub/grub.cfg? (On 2026-07-28
#     it did not: grub-installer left GRUB_CMDLINE_LINUX="".)
#   * is there any route to a graphical seat, or does sddm hang forever?
#   * is the EFI removable fallback OUR bootloader, or a stale systemd-boot
#     with an empty loader/entries?
#
# This answers all of them in a VM, on a throwaway qcow2, in one command.
#
# It is the Debian counterpart of
# scripts/build/ubuntu-autoinstall/verify-full-install-in-vm.sh and shares its
# inspector (scripts/build/lib/inspect-installed-disk.sh). The two installers
# are genuinely different mechanisms — d-i + preseed vs Subiquity + autoinstall
# — so the harnesses differ, but the assertions must not.
#
# ── WHAT IS ADDED FOR THE VM, AND WHY IT IS NOT IN THE SHIPPED PRESEED ──────
#
# The shipped preseed deliberately does NOT answer the destructive
# confirmations or set a password:
#
#   * the operator picks and confirms the target disk. A device name is not an
#     identity — the preseed once hardcoded "skip nvme0n1" on the assumption
#     that nvme0n1 was the running OS, and that assumption expired and selected
#     exactly the disk it was written to protect (2026-07-27).
#   * no plaintext password ever ships. The preseed once carried
#     `root-password sovereign` inside every ISO, world-readable at
#     /simple-cdd/default.preseed (SDD-015).
#
# Both are answered HERE, at runtime, into scratch, against a throwaway qcow2
# that is the only disk the VM can see. The generated preseed is never written
# into the repo and never into the shipped ISO. The password is minted per run
# and recorded in scratch only.
#
# Usage:  verify-full-install-in-vm.sh [iso]
# Exit:   0 = the installed system passes every assertion
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="$(cd "${HERE}/../../.." && pwd)"
ISO="${1:-${REPO}/build/sain-01/output/sain-01-installer.iso}"
WORK="${SOVEREIGN_OS_VMTEST_WORK:-/var/tmp/sovereign-debian-vmtest}"
DISK_GB="${SOVEREIGN_OS_VMTEST_DISK_GB:-24}"
BOOT_TIMEOUT="${SOVEREIGN_OS_VMTEST_TIMEOUT:-3600}"   # 60 min: d-i is slower
VM_DISK="/dev/vda"

red() { printf '\033[31m%s\033[0m\n' "$*"; }
grn() { printf '\033[32m%s\033[0m\n' "$*"; }
log() { printf '\033[36m━━ vmtest: %s\033[0m\n' "$*" >&2; }

[ -r "${ISO}" ] || { red "no ISO at ${ISO}"; exit 1; }
for t in qemu-system-x86_64 xorriso qemu-img openssl; do
  command -v "$t" >/dev/null || { red "missing ${t}"; exit 1; }
done
OVMF_CODE=/usr/share/OVMF/OVMF_CODE_4M.fd
OVMF_VARS=/usr/share/OVMF/OVMF_VARS_4M.fd
[ -r "${OVMF_CODE}" ] || { red "no OVMF (sudo apt install ovmf)"; exit 1; }

rm -rf "${WORK}"; mkdir -p "${WORK}/cdd"
log "scratch: ${WORK}"

# ── 1. the VM-ONLY preseed ──────────────────────────────────────────────────
# Start from the SHIPPED file so this tests what we ship. Anything else that
# differs would make the whole exercise a lie.
PS="${WORK}/cdd/default.preseed"
xorriso -indev "${ISO}" -osirrox on -extract /simple-cdd/default.preseed "${PS}" \
  >/dev/null 2>&1 || { red "could not read the preseed from ${ISO}"; exit 1; }
# xorriso -osirrox yields mode 0444; every later write fails without this.
chmod u+w "${PS}"
log "extracted the shipped preseed ($(wc -l <"${PS}") lines)"

_pw="$(openssl rand -base64 18)"
_hash="$(printf '%s' "${_pw}" | openssl passwd -6 -stdin)"
# Record the throwaway credential in SCRATCH. When a VM install boots to
# something unexpected, being unable to log in and look is a needless dead end
# (2026-07-29). Never the repo, never the ISO.
printf 'root / %s\njfortin / %s\n' "${_pw}" "${_pw}" > "${WORK}/vm-credentials.txt"
chmod 0600 "${WORK}/vm-credentials.txt"

cat >> "${PS}" <<PRESEED

############################################################################
#### VM-TEST ONLY — generated by verify-full-install-in-vm.sh at runtime.
#### NEVER committed, never shipped. Answers exactly the two things the
#### shipped preseed leaves to the operator: the destructive disk write and
#### the passwords.
############################################################################

### the target disk. In the VM this is the ONLY disk attached, so there is
### nothing else it could pick even if this line were wrong.
d-i partman-auto/disk string ${VM_DISK}
d-i grub-installer/bootdev string ${VM_DISK}

### the destructive confirmations, all of them. Missing ANY one of these stops
### d-i at a dialog and the run dies on timeout with no useful output.
d-i partman-lvm/device_remove_lvm boolean true
d-i partman-md/device_remove_md boolean true
d-i partman-lvm/confirm boolean true
d-i partman-lvm/confirm_nooverwrite boolean true
d-i partman-partitioning/confirm_write_new_label boolean true
d-i partman/confirm boolean true
d-i partman/confirm_nooverwrite boolean true
d-i partman-basicfilesystems/no_mount_point boolean false

### throwaway credentials, minted per run
d-i passwd/root-password-crypted password ${_hash}
d-i passwd/user-password-crypted password ${_hash}

### never block on a prompt in an unattended run
d-i preseed/late_command_failed note
d-i finish-install/keep-consoles boolean false
PRESEED
log "appended the VM-only answers (disk ${VM_DISK}, throwaway password)"

# ── 2. remaster the test ISO ────────────────────────────────────────────────
TEST_ISO="${WORK}/vmtest.iso"
log "remastering a VM-only ISO"
# COPY then modify IN PLACE with `-boot_image any keep`.
#
# `-indev A -outdev B -boot_image any replay` works when A is a pristine distro
# ISO, but this input is ALREADY a build product and replay then cannot
# re-derive the second El Torito image:
#     SORRY : Cannot enable EL Torito boot image #2 because it is not a data file
# `keep` on an in-place device preserves both boot images (2026-07-29).
cp "${ISO}" "${TEST_ISO}"
xorriso -dev "${TEST_ISO}" -boot_image any keep \
  -rm /simple-cdd/default.preseed -- \
  -map "${PS}" /simple-cdd/default.preseed -- >/dev/null 2>&1 \
  || { red "remaster failed"; exit 1; }

# Prove the ISO carries what we just wrote. A remaster that silently no-ops
# would produce an install that stops at the first dialog and a 60-minute
# timeout with nothing to show for it.
xorriso -indev "${TEST_ISO}" -osirrox on \
  -extract /simple-cdd/default.preseed "${WORK}/readback.preseed" >/dev/null 2>&1
if ! grep -q "partman/confirm boolean true" "${WORK}/readback.preseed"; then
  red "the remastered ISO does NOT carry the VM-only answers — refusing to run"
  exit 1
fi
grn "verified: the test ISO carries the VM-only preseed"

# ── 3. install ──────────────────────────────────────────────────────────────
cp "${OVMF_VARS}" "${WORK}/vars.fd"; chmod u+w "${WORK}/vars.fd"
qemu-img create -f qcow2 "${WORK}/disk.qcow2" "${DISK_GB}G" >/dev/null
log "installing (up to $((BOOT_TIMEOUT/60)) min) — disk ${DISK_GB}G, THE ONLY disk attached"
# The installer writes nothing to serial (the profile's kernel line puts tty0
# last so the physical display keeps /dev/console), so over an hour there is no
# way to tell "working" from "wedged" except watching the qcow2 grow. The QMP
# socket makes the framebuffer capturable:
#     echo '{"execute":"qmp_capabilities"}{"execute":"screendump","arguments":
#            {"filename":"/tmp/s.ppm"}}' | socat - UNIX-CONNECT:<work>/qmp.sock
log "  progress: watch ${WORK}/disk.qcow2 grow, or screendump via ${WORK}/qmp.sock"
set +e
timeout "${BOOT_TIMEOUT}" qemu-system-x86_64 \
  -machine q35,accel=kvm -cpu host -m 8G -smp 6 \
  -drive if=pflash,format=raw,unit=0,readonly=on,file="${OVMF_CODE}" \
  -drive if=pflash,format=raw,unit=1,file="${WORK}/vars.fd" \
  -drive file="${WORK}/disk.qcow2",if=virtio,format=qcow2 \
  -cdrom "${TEST_ISO}" -boot d -display none -vga std \
  -serial "file:${WORK}/serial.log" -no-reboot \
  -qmp "unix:${WORK}/qmp.sock,server,nowait" \
  >"${WORK}/qemu.log" 2>&1
_rc=$?
set -e
log "qemu exited rc=${_rc} (-no-reboot: the VM stops when the install reboots)"
if [ "${_rc}" -eq 124 ]; then
  red "TIMED OUT after $((BOOT_TIMEOUT/60)) min — d-i is probably sitting at a"
  red "dialog this preseed does not answer. Screendump via ${WORK}/qmp.sock"
  red "on the next run to see which one."
fi

# A disk that never grew means the install never partitioned. Say so plainly
# rather than letting the inspector report 15 confusing failures.
_used=$(qemu-img info --output=json "${WORK}/disk.qcow2" 2>/dev/null \
        | python3 -c 'import json,sys; print(json.load(sys.stdin).get("actual-size",0))' 2>/dev/null || echo 0)
if [ "${_used}" -lt 104857600 ]; then
  red "the target disk is still essentially empty ($((_used/1048576)) MiB used)."
  red "The install never wrote anything — check ${WORK}/qemu.log and the QMP"
  red "screendump. Not running the inspector on an empty disk."
  exit 1
fi
log "target disk holds $((_used/1048576)) MiB — the install wrote something"

# ── 4. inspect the INSTALLED disk ───────────────────────────────────────────
# Read-only, unprivileged: debugfs against the extracted root LV. Nothing on the
# host is touched and no mount is needed.
log "inspecting the installed disk"
"${REPO}/scripts/build/lib/inspect-installed-disk.sh" "${WORK}/disk.qcow2"
