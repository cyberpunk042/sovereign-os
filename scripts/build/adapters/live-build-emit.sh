#!/usr/bin/env bash
# scripts/build/adapters/live-build-emit.sh — emit Debian live-build config
# from sovereign-os profile YAML. Alt-A substrate adapter per SDD-003.
#
# Usage: live-build-emit.sh <profile.yaml> <output-dir>
#
# Produces a live-build config/ tree:
#   config/auto/config              — lb_config invocation
#   config/auto/build               — build script
#   config/auto/clean               — clean script
#   config/package-lists/sovereign.list.chroot  — package list
#   config/includes.chroot/         — file overlay (populated by whitelabel render)
#   config/hooks/normal/            — first-boot hook
#   config/bootloaders/grub-pc/     — GRUB theming (optional)

__SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=../lib/common.sh
. "${__SCRIPT_DIR}/../lib/common.sh"

profile_yaml="${1:?usage: live-build-emit.sh <profile.yaml> <out-dir>}"
out_dir="${2:?usage: live-build-emit.sh <profile.yaml> <out-dir>}"

require_file "${profile_yaml}"

# FAIL FAST on the substrate tool. `lb` was only required in step 07 — AFTER
# this step had already spent ~20 minutes debootstrapping the complete target
# rootfs. The operator paid for the whole build to be told a package was
# missing (2026-07-26: "missing required command: lb"). A missing tool is
# knowable in one second; check it before doing any expensive work.
require_command lb "sudo apt install live-build — or run scripts/install/bootstrap-host.sh"

mkdir -p "${out_dir}"/config/{auto,package-lists,includes.chroot,hooks/normal,bootloaders}

profile_id="$("${PYTHON3}" -c "
import yaml, sys
with open('${profile_yaml}') as f:
    print(yaml.safe_load(f)['identity']['id'])
")"

log_info "emitting live-build config for profile=${profile_id} → ${out_dir}"

# ---- config/auto/config — lb_config arguments ----
cat > "${out_dir}/config/auto/config" <<'EOF'
#!/usr/bin/env bash
# auto-generated by sovereign-os live-build adapter
set -euo pipefail

lb config noauto \
    --distribution trixie \
    --archive-areas "main contrib non-free non-free-firmware" \
    --architectures amd64 \
    --binary-images iso-hybrid \
    --bootappend-live "boot=live components console=tty0 console=ttyS0,115200" \
    --apt-source-archives false \
    --memtest none \
    --iso-volume "Sovereign-OS-${SOVEREIGN_OS_PROFILE:-sain-01}" \
    --iso-application "Sovereign OS" \
    --iso-publisher "cyberpunk042" \
    "$@"
EOF
chmod +x "${out_dir}/config/auto/config"

# ---- config/auto/build ----
cat > "${out_dir}/config/auto/build" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
lb build "$@"
EOF
chmod +x "${out_dir}/config/auto/build"

# ---- config/auto/clean ----
cat > "${out_dir}/config/auto/clean" <<'EOF'
#!/usr/bin/env bash
set -euo pipefail
lb clean "$@"
EOF
chmod +x "${out_dir}/config/auto/clean"

# ---- package-lists/sovereign.list.chroot — from profile.packages ----
# INSTALLER: keep the LIVE env minimal — the profile's app/driver packages
# (nvidia, zfs, kde, …) install onto the TARGET at install-time, NOT into the
# live USB (and many are contrib/non-free that the live chroot wouldn't resolve).
# The installer tooling is a separate list (sovereign-installer.list.chroot).
if [ "${SOVEREIGN_OS_ARTIFACT:-image}" = "installer" ]; then
  printf '# installer live env — minimal by design; the profile package set installs\n# onto the target at install-time (see install-sovereign-root.sh), not here.\n' \
    > "${out_dir}/config/package-lists/sovereign.list.chroot"
else
"${PYTHON3}" - <<PY > "${out_dir}/config/package-lists/sovereign.list.chroot"
import yaml
with open("${profile_yaml}") as f:
    p = yaml.safe_load(f)
base = (p.get("packages") or {}).get("base") or []
profile_pkgs = (p.get("packages") or {}).get("profile") or []
deny = (p.get("packages") or {}).get("deny") or []

print(f"# auto-generated from profiles/${profile_id}.yaml")
print(f"# base ({len(base)}):")
for pkg in base:
    if any(pkg.startswith(d) for d in deny):
        continue
    print(pkg)
print(f"# profile ({len(profile_pkgs)}):")
for pkg in profile_pkgs:
    if pkg.startswith("linux-image-") or pkg.startswith("linux-headers-"):
        # custom kernel ships separately via includes.chroot
        continue
    if any(pkg.startswith(d) for d in deny):
        continue
    print(pkg)
PY
fi

# ---- config/archives/sovereign-deny.pref.chroot + purge hook (sovereignty) ----
# The profile's packages.deny is a no-phone-home policy (snapd, apport, whoopsie,
# popularity-contest, ubuntu-advantage, …). Filtering the explicit package list
# above does NOT stop a denied daemon pulled in as a transitive dependency, so
# enforce it: an apt pin (Pin-Priority -1 = never install; blocks Recommends/
# Suggests) plus a belt-and-suspenders purge hook that runs after package install.
mkdir -p "${out_dir}/config/archives"
"${PYTHON3}" - <<PY
import yaml, pathlib
with open("${profile_yaml}") as f:
    p = yaml.safe_load(f)
deny = (p.get("packages") or {}).get("deny") or []
out = pathlib.Path("${out_dir}")
if deny:
    pin = "Package: " + " ".join(deny) + "\nPin: release o=*\nPin-Priority: -1\n"
    (out / "config" / "archives" / "sovereign-deny.pref.chroot").write_text(pin)
    hook = out / "config" / "hooks" / "normal" / "0005-purge-sovereign-deny.hook.chroot"
    hook.write_text(
        "#!/bin/sh\n"
        "# sovereignty: purge any phone-home / telemetry package that slipped in\n"
        "apt-get purge -y " + " ".join(deny) + " 2>/dev/null || true\n"
    )
    hook.chmod(0o755)
    print(f"  deny-list enforced: apt pin (-1) + purge hook for {len(deny)} package(s)")

# kernel.modules.load_at_boot → /etc/modules-load.d/ (includes.chroot overlay).
# Declared in the profile but enforced by nothing — without this the listed
# modules (zfs / nvidia / vfio_pci) relied on implicit load paths only.
load_at_boot = ((p.get("kernel") or {}).get("modules") or {}).get("load_at_boot") or []
if load_at_boot:
    mld = out / "config" / "includes.chroot" / "etc" / "modules-load.d"
    mld.mkdir(parents=True, exist_ok=True)
    (mld / "sovereign-os.conf").write_text(
        "# kernel.modules.load_at_boot (profile ${profile_id})\n"
        + "\n".join(load_at_boot) + "\n"
    )
    print(f"  modules-load.d enforced for {len(load_at_boot)} module(s)")
PY

# ---- hooks/normal/0010-sovereign-first-boot.hook.chroot ----
cat > "${out_dir}/config/hooks/normal/0010-sovereign-first-boot.hook.chroot" <<'EOF'
#!/usr/bin/env bash
# Runs inside the chroot during live-build assembly.
# Installs the first-boot greeting service that runs on installed-system first login.
set -euo pipefail

# Install sovereign-os scripts to /opt
if [ -d /opt/sovereign-os/scripts ]; then
  echo "sovereign-os scripts already present"
else
  echo "first-boot hook: sovereign-os scripts to be staged at install time"
fi
EOF
chmod +x "${out_dir}/config/hooks/normal/0010-sovereign-first-boot.hook.chroot"

# ---- Empty includes.chroot — populated by whitelabel render step ----
mkdir -p "${out_dir}/config/includes.chroot"

# ---- INSTALLER artifact (SOVEREIGN_OS_ARTIFACT=installer) ----
# Turn the plain live image into a bootable INSTALLER: bake the reflash-root
# payload (repo + custom kernel .debs), the autostart installer service, an
# answers template, and the tools the installer needs, into the live squashfs.
# Booting the ISO then runs scripts/install/installer-tui.sh on tty1, which
# installs the mutable sovereign-os system onto an internal disk (never the USB).
if [ "${SOVEREIGN_OS_ARTIFACT:-image}" = "installer" ]; then
  log_info "installer artifact — staging reflash-root payload into the live ISO"
  _repo="${SOVEREIGN_OS_ROOT:-$(cd "${__SCRIPT_DIR}/../../.." && pwd)}"
  _inc="${out_dir}/config/includes.chroot"

  # (a) the repo the installer scripts + GUI stage need, at /opt/sovereign-os
  mkdir -p "${_inc}/opt/sovereign-os"
  for d in scripts webapp profiles config systemd share; do
    [ -d "${_repo}/${d}" ] && cp -a "${_repo}/${d}" "${_inc}/opt/sovereign-os/"
  done

  # (b) the custom kernel .debs the installed root boots (found by
  #     install-sovereign-root.sh at /opt/sovereign-os/kernel-debs)
  mkdir -p "${_inc}/opt/sovereign-os/kernel-debs"
  _kdir="${SOVEREIGN_OS_KERNEL_DEBS_DIR:-}"
  [ -z "${_kdir}" ] && [ -r /root/.sovereign-os/build-state/env-kernel-debs.sh ] \
    && . /root/.sovereign-os/build-state/env-kernel-debs.sh || true
  for cand in "${SOVEREIGN_OS_KERNEL_DEBS_DIR:-}" /mnt/kernel_forge; do
    if [ -n "${cand}" ] && ls "${cand}"/linux-image-6.12.0_*.deb >/dev/null 2>&1; then
      cp -a "${cand}"/linux-{image,headers}-6.12.0_*.deb "${_inc}/opt/sovereign-os/kernel-debs/" 2>/dev/null || true
      break
    fi
  done
  if ! ls "${_inc}/opt/sovereign-os/kernel-debs/"linux-image-*.deb >/dev/null 2>&1; then
    log_warn "installer: custom kernel .debs NOT found (set SOVEREIGN_OS_KERNEL_DEBS_DIR); the installed root will fall back to a stock kernel"
  fi

  # (c) the autostart installer service + answers template
  mkdir -p "${_inc}/etc/systemd/system/multi-user.target.wants"
  cp "${_repo}/scripts/install/sovereign-installer.service" "${_inc}/etc/systemd/system/"
  ln -sf ../sovereign-installer.service \
    "${_inc}/etc/systemd/system/multi-user.target.wants/sovereign-installer.service"
  cat > "${_inc}/opt/sovereign-os/install-answers.env" <<'ANSWERS'
# sovereign-os installer answers (edit or override in the TUI).
# Unattended: also set SOVEREIGN_OS_NONINTERACTIVE=1 and a TARGET_DISK.
SOVEREIGN_OS_KEYMAP=us
SOVEREIGN_OS_LOCALE=en_US.UTF-8
SOVEREIGN_OS_TIMEZONE=UTC
SOVEREIGN_OS_USER=jfortin
SOVEREIGN_OS_USER_UID=1000
# PLACEHOLDER — the installer PROMPTS for this and refuses to install on the
# default unless SOVEREIGN_OS_ALLOW_DEFAULT_PASSWORD=1. Set a real value here
# only for a deliberate unattended build.
SOVEREIGN_OS_USER_PASS=sovereign
SOVEREIGN_OS_ROOT_PASS=sovereign
SOVEREIGN_OS_FRONTEND=kde-plasma
# OFFLINE install: lay the pre-built rootfs (base+kernel+KDE+cockpit) onto the LV
# instead of debootstrap/apt over the network. Baked at this path in the ISO.
SOVEREIGN_OS_ROOTFS_SQUASHFS=/opt/sovereign-os/rootfs.squashfs
# SOVEREIGN_OS_TARGET_DISK=/dev/nvme1n1
ANSWERS

  # (d) the tools the installer runs in the LIVE env (unsquashfs lays the rootfs;
  #     debootstrap/lvm/gdisk/grub are the online-fallback + partitioning tools)
  printf '# installer tooling\ndebootstrap\nsquashfs-tools\nlvm2\ngdisk\ngrub-efi-amd64\ngrub-efi-amd64-signed\nefibootmgr\nrsync\nwhiptail\ndosfstools\n' \
    > "${out_dir}/config/package-lists/sovereign-installer.list.chroot"

  # (f) the COMPLETE pre-built target rootfs — the OFFLINE install payload (base +
  #     stock kernel + KDE + sovereign-os cockpit). Built once by
  #     build-target-rootfs.sh, cached at build/<profile>/rootfs.squashfs across
  #     builds (rebuild with SOVEREIGN_OS_REBUILD_ROOTFS=1). This is the bulk of
  #     the ISO's size — the "contains everything" payload.
  _rootfs_cache="${_repo}/build/${profile_id}/rootfs.squashfs"
  if [ "${SOVEREIGN_OS_REBUILD_ROOTFS:-0}" != "1" ] && [ -s "${_rootfs_cache}" ]; then
    log_info "reusing cached target rootfs: ${_rootfs_cache} ($(du -h "${_rootfs_cache}" | cut -f1))"
  else
    log_info "building the complete target rootfs (offline payload — base+kernel+KDE+cockpit, ~15-20 min)…"
    _stage="$(mktemp -d /var/tmp/sovereign-rootfs.XXXXXX)"
    SOVEREIGN_OS_STAGE_DIR="${_stage}" \
    SOVEREIGN_OS_ROOTFS_OUT="${_rootfs_cache}" \
    SOVEREIGN_OS_FRONTEND="${SOVEREIGN_OS_FRONTEND:-kde-plasma}" \
    SOVEREIGN_OS_ROOT="${_repo}" \
      bash "${_repo}/scripts/build/build-target-rootfs.sh"
    rm -rf "${_stage}"
  fi
  cp -a "${_rootfs_cache}" "${_inc}/opt/sovereign-os/rootfs.squashfs"

  # (e) UEFI-bootable installer (shim-signed chain; iso-hybrid also keeps BIOS).
  #     Appended to the lb config args so the ISO boots on the ProArt's UEFI.
  sed -i 's#    "\$@"#    --bootloaders "grub-efi" \\\n    --iso-application "Sovereign OS Installer" \\\n    "$@"#' \
    "${out_dir}/config/auto/config"

  # (g) boot-config binary hook — runs late in `lb binary`, AFTER live-build has
  #     generated grub.cfg/isolinux.cfg, and rewrites them deterministically
  #     (live-build's --bootappend-live proved unreliable). It: AUTO-BOOTS the
  #     installer (timeout 3s, default 0 — no more "Testing" menu the operator
  #     had to pick from), drops `quiet splash` so boot progress is visible, adds
  #     a serial console (real-hw harmless, lets QEMU/OVMF watch the boot), and
  #     routes GRUB itself to serial.
  cat > "${out_dir}/config/hooks/normal/9990-installer-bootcfg.hook.binary" <<'BOOTCFG'
#!/bin/sh
set -e
_cmdline_fix() { sed -i -e 's/quiet splash//g' \
  -e 's#boot=live components#boot=live components console=tty0 console=ttyS0,115200#g' "$1"; }
for cfg in binary/boot/grub/grub.cfg binary/efi/boot/grub.cfg binary/boot/grub/x86_64-efi/grub.cfg; do
  [ -f "$cfg" ] || continue
  grep -q 'set timeout=' "$cfg" && sed -i 's/^set timeout=.*/set timeout=3/' "$cfg" \
    || sed -i '1i set timeout=3\nset default=0' "$cfg"
  grep -q 'terminal_output' "$cfg" || sed -i '1i serial --unit=0 --speed=115200\nterminal_input console serial\nterminal_output console serial' "$cfg"
  _cmdline_fix "$cfg"
done
for cfg in binary/isolinux/isolinux.cfg binary/isolinux/live.cfg binary/isolinux/menu.cfg binary/isolinux/stdmenu.cfg; do
  [ -f "$cfg" ] || continue
  sed -i 's/^timeout .*/timeout 30/' "$cfg" 2>/dev/null || true
  _cmdline_fix "$cfg"
done
echo "installer bootcfg: auto-boot (timeout 3s) + serial console applied"
BOOTCFG
  chmod +x "${out_dir}/config/hooks/normal/9990-installer-bootcfg.hook.binary"

  log_info "installer payload staged: repo + kernel-debs + service + answers + tooling + bootcfg"
fi

# ---- README at output root ----
cat > "${out_dir}/README.md" <<EOF
# live-build config for sovereign-os profile \`${profile_id}\`

Auto-generated by \`scripts/build/adapters/live-build-emit.sh\`.

Build:
    cd <this dir>
    sudo lb build

Config:
    - config/auto/config   — lb_config flags (Debian Trixie, ISO-hybrid)
    - config/package-lists/sovereign.list.chroot   — from profile.packages
    - config/includes.chroot/   — populated by whitelabel render
    - config/hooks/normal/      — first-boot hook

NOTE: This is the ALT-A substrate path (live-build). The PRIMARY path
per SDD-003 recommendation is mkosi-on-Debian-13. Adapter exists so
operator can swap at Stage Gate 2 without rewriting profile bodies.
EOF

log_info "live-build config emitted to ${out_dir}"
log_info "  files:"
find "${out_dir}" -maxdepth 4 -type f | while read -r f; do
  log_info "    ${f}"
done
